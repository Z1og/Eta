def parse_spec_watch(tok):
    """w:0xADDR:LEN:ACCESS -> dict; validated with hw_watch-style rules."""
    parts = tok.split(":")
    if len(parts) != 4 or parts[0] != "w":
        raise ValueError("watch spec must be w:0xADDR:LEN:ACCESS, got %r" % tok)
    addr = int(parts[1], 0)
    length = int(parts[2], 0)
    access = parts[3]
    if length not in range(1, 9):
        raise ValueError("watch length must be 1..8")
    if access not in ("r", "w", "rw"):
        raise ValueError("watch access must be r/w/rw")
    if (addr & 7) + length > 8:
        raise ValueError("watch 0x%x+%d crosses its aligned 8-byte window"
                         % (addr, length))
    return {"addr": "0x%x" % addr, "len": length, "access": access}


def parse_spec_break(tok, set_reg=None):
    """b:0xADDR[:reg=value] -> dict."""
    parts = tok.split(":")
    if not parts or parts[0] != "b" or len(parts) < 2:
        raise ValueError("break spec must be b:0xADDR, got %r" % tok)
    addr = int(parts[1], 0)
    if addr & 3:
        raise ValueError("break PC 0x%x is not 4-byte aligned" % addr)
    row = {"pc": "0x%x" % addr}
    if set_reg:
        m = re.match(r"^(x\d+)=(0x[0-9a-fA-F]+|\d+)$", set_reg)
        if not m or int(m.group(1)[1:]) > 30:
            # x31 is sp's slot in user_pt_regs and the array ends at x30: an
            # index past 30 writes sp, pc, pstate, or off the frame. sp/pc are
            # refused too: the template has no rewrite path for them, and a
            # generate that "succeeds" while silently dropping the action is
            # the misleading kind of success
            raise ValueError("--set-reg must be x0..x30=<value> (sp/pc have no "
                             "rewrite path in the template), got %r" % set_reg)
        row["set_reg"] = m.group(1)
        row["set_value"] = m.group(2)
    return row


