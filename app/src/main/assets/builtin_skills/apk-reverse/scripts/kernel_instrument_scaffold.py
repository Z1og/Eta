KPM_C = r'''// SPDX-License-Identifier: GPL-2.0
/*
 * kwatch.c -- invisible hardware watchpoints + register rewrite at trap,
 * as a KernelPatch / APatch KPM.
 *
 * {unverified}
 *
 * Design notes that are load-bearing:
 *   - The arm64 debug registers are owned by the kernel perf/breakpoint
 *     layer. A KPM does not poke DBGWVR/DBGWCR directly (it cannot, from
 *     kernel C code safely); it asks perf to create a breakpoint event on the
 *     target task, and perf programs the slots at context switch.
 *   - The overflow callback receives the interrupted context's pt_regs. That
 *     is where the "event injection" half lives: rewriting regs->regs[n]
 *     changes what the userspace instruction stream sees after the trap.
 *     This is mechanically what a ptrace stop does -- but it was never run
 *     here, and on some interrupt contexts you must not sleep or allocate.
 *     LOGGING IS SAFE; REGISTER REWRITING IS EXPERIMENTAL.
 *   - TracerPid stays 0: no ptrace relationship is ever created.
 */
#include <linux/types.h>
#include <linux/printk.h>
#include <linux/perf_event.h>
#include <linux/hw_breakpoint.h>
#include <kpmodule.h>

KPM_NAME("{id}");
KPM_VERSION("{version}");
KPM_LICENSE("GPL");
KPM_AUTHOR("apk-reverse");
KPM_DESCRIPTION("config-driven invisible watchpoints on one task");

/* kfunc declarations must NOT carry `extern` (see kernelsu_syscall_mask.py's
 * KPM notes): tentative definitions allocate .bss slots the loader fills. */
int kfunc_def(find_task_by_vpid)(int vnr);
int kfunc_def(perf_event_create_kernel_counter)(
    struct perf_event_attr *attr, int cpu, void *task,
    void *overflow_handler, void *context);
int kfunc_def(perf_event_release_kernel)(void *event);

static struct perf_event *events[{max_events}];
static int nevents = 0;

struct wp_cfg {{
    u64 addr; int len; int bp_type; const char *label;
}};

/* PERF_TYPE_BREAKPOINT = 5; bp_type: 1=read 2=write 4=execute (uapi) */
static struct wp_cfg cfg[] = {{
{cfg_rows}
}};

static void wp_hit(struct perf_event *event, void *data, struct pt_regs *regs)
{{
    /* Runs on every hit, in interrupt context on the hitting CPU, for EVERY
     * event registered below -- watch and break alike. The generated body is
     * an UNFILTERED printk: add a cheap first-statement filter (event/addr)
     * before treating any hit as signal on a hot path. */
    printk(KERN_INFO "KWATCH hit pc=0x%llx x0=0x%llx x1=0x%llx\n",
           (unsigned long long)regs->pc,
           (unsigned long long)regs->regs[0],
           (unsigned long long)regs->regs[1]);
{inject_rows}
}}

static int kwatch_init(void) {{
    struct task_struct *task = (void *)(unsigned long)kfunc_find_task_by_vpid({pid});
    if (!task) {{
        printk(KERN_ERR "KWATCH: no task pid={pid}\n");
        return -1;
    }}
    for (int i = 0; i < sizeof(cfg)/sizeof(cfg[0]); i++) {{
        struct perf_event_attr attr;
        memset(&attr, 0, sizeof(attr));
        attr.type = 5 /* PERF_TYPE_BREAKPOINT */;
        attr.sample_period = 1;  /* hw_breakpoint_init's firing line: a period
                                  * of 0 is a non-sampling event and wp_hit
                                  * never runs -- armed but silent */
        attr.bp_type = cfg[i].bp_type;
        attr.bp_addr = cfg[i].addr;
        attr.bp_len = cfg[i].len;
        attr.size = sizeof(attr);
        attr.disabled = 0;
        attr.inherit = 0;
        events[nevents] = (void *)(unsigned long)
            kfunc_perf_event_create_kernel_counter(
                &attr, -1 /* any cpu */, task, wp_hit, NULL);
        if (IS_ERR_OR_NULL(events[nevents])) {{
            printk(KERN_ERR "KWATCH: slot %d failed (no slots left? perf bp layer off?)\n", i);
            events[nevents] = NULL;
        }} else {{
            nevents++;
        }}
    }}
    printk(KERN_INFO "KWATCH armed %d events on pid={pid}\n", nevents);
    return 0;
}}

static void kwatch_exit(void) {{
    for (int i = 0; i < nevents; i++)
        if (events[i])
            kfunc_perf_event_release_kernel(events[i]);
    printk(KERN_INFO "KWATCH released %d events\n", nevents);
}}

KPM_INIT(kwatch_init);
KPM_EXIT(kwatch_exit);
'''

LKM_C = r'''// SPDX-License-Identifier: GPL-2.0
/*
 * kwatch.c -- invisible hardware watchpoints on one task, as an out-of-tree LKM.
 *
 * {unverified}
 *
 * Gates that decide whether this file is even buildable: kernel source
 * matching the device's exact vermagic; and on >= 5.7 the unexported-symbol
 * problem (find_task_by_vpid is not exported on every tree -- resolve it or
 * take the pid from a syscall parameter instead).
 * Build: make -C <kernel-src> M=$PWD modules
 */
#include <linux/module.h>
#include <linux/perf_event.h>
#include <linux/hw_breakpoint.h>
#include <linux/sched.h>
#include <linux/pid.h>
#include <linux/printk.h>

struct wp_cfg {{
    u64 addr; int len; int bp_type;
}};
static struct wp_cfg cfg[] = {{
{cfg_rows}
}};
static struct perf_event *events[{max_events}];
static int nevents = 0;

static void wp_hit(struct perf_event *event, struct perf_sample_data *data,
                   struct pt_regs *regs)
{{
    printk(KERN_INFO "KWATCH hit pc=0x%llx x0=0x%llx x1=0x%llx\n",
           (unsigned long long)regs->pc,
           (unsigned long long)regs->regs[0],
           (unsigned long long)regs->regs[1]);
{inject_rows}
}}

static int __init kwatch_init(void)
{{
    struct task_struct *task;
    rcu_read_lock();
    task = pid_task(find_vpid({pid}), PIDTYPE_PID);
    if (task)
        /* pin the task past the RCU section: registration below can sleep,
         * and an unpinned pointer can be freed after a task exit in between */
        get_task_struct(task);
    rcu_read_unlock();
    if (!task) {{
        pr_err("KWATCH: no task pid={pid}\n");
        return -ESRCH;
    }}
    for (int i = 0; i < ARRAY_SIZE(cfg); i++) {{
        struct perf_event_attr attr;
        /* sets size/type/pinned/sample_period=1: a zero period is a
         * non-sampling event whose overflow callback (wp_hit) never runs */
        hw_breakpoint_init(&attr);
        attr.bp_type = cfg[i].bp_type;
        attr.bp_addr = cfg[i].addr;
        attr.bp_len = cfg[i].len;
        /* the user-task API is (attr, handler, context, task): the per-cpu
         * `register_wide_hw_breakpoint` family cannot arm on one target */
        events[nevents] = register_user_hw_breakpoint(
            &attr, wp_hit, NULL, task);
        if (IS_ERR(events[nevents])) {{
            pr_err("KWATCH: slot %d failed\n", i);
            events[nevents] = NULL;
        }} else {{
            nevents++;
        }}
    }}
    pr_info("KWATCH armed %d events on pid={pid}\n", nevents);
    put_task_struct(task);
    return 0;
}}
module_init(kwatch_init);

static void __exit kwatch_exit(void)
{{
    int i;
    for (i = 0; i < nevents; i++)
        if (events[i])
            unregister_hw_breakpoint(events[i]);
    pr_info("KWATCH released %d events\n", nevents);
}}
module_exit(kwatch_exit);
MODULE_LICENSE("GPL");
MODULE_DESCRIPTION("config-driven invisible watchpoints on one task");
'''

BP_TYPE = {"r": "1 /* read */", "w": "2 /* write */", "rw": "3 /* rw */", "x": "4 /* execute */"}

INJECT_LOG = "    /* action: log only (safe in any context) */"
INJECT_SET = ("    /* action: set-reg -- EXPERIMENTAL, never run by this repository.\n"
              "     * Rewriting the interrupted frame's register is what a ptrace\n"
              "     * stop does mechanically; doing it from a perf overflow callback\n"
              "     * was not tested anywhere here. The rewrite is guarded by its\n"
              "     * breakpoint's own event so a watchpoint hit in this same callback\n"
              "     * cannot run it. */\n"
              "    if (event && (event->attr.bp_type & 4 /* HW_BREAKPOINT_X */)\n"
              "        && event->attr.bp_addr == {addr}) {{\n"
              "        regs->regs[{idx}] = {value};\n"
              "    }}")


def render_cfg_rows(watches, breaks, for_kpm):
    """Spec dicts -> wp_cfg C rows for the kernel template."""
    rows = []
    for w in watches:
        bp = BP_TYPE[w["access"]]
        rows.append('    { .addr = %s, .len = %d, .bp_type = %s },  /* watch %s:%s */'
                    % (w["addr"], w["len"], bp, w["addr"], w["access"]))
    for b in breaks:
        # wp_cfg declares addr/len/bp_type and has no `pc` member; an execution
        # breakpoint is .addr with bp_type HW_BREAKPOINT_X (4) and the machine
        # word (8 on arm64) as its length
        rows.append('    { .addr = %s, .len = 8, .bp_type = 4 /* HW_BREAKPOINT_X */ },'
                    '  /* execute breakpoint */'
                    % b["pc"])
    return "\n".join(rows)


def render_inject_rows(breaks):
    """Break actions -> guarded callback body rows."""
    parts = [INJECT_LOG]
    for b in breaks:
        if b.get("set_reg"):
            reg = b["set_reg"]
            idx = reg[1:] if reg.startswith("x") else None
            if idx is None:
                parts.append("    /* set-reg on %s not expressible in pt_regs by index; "
                             "extend the template */" % reg)
                continue
            parts.append(INJECT_SET.format(addr=b["pc"], idx=idx, value=b["set_value"]))
    return "\n".join(parts)


