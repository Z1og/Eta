#!/usr/bin/env python3
"""kernel_instrument_scaffold.py -- generate a kernel-side instrumentation scaffold:
invisible watchpoints and event injection from a driver.

What "event injection" means here, and what this generates
---------------------------------------------------------
The escalation this scaffold exists for: you want to observe or alter a target
process with **no ptrace** (so `TracerPid` stays 0), **no injected thread**,
**no code modification** (so page checksums stay clean) and **no DBI cache**.
Only a kernel-side driver can do all four at once, because the hardware debug
registers can be programmed on the target's behalf from the kernel, and the
overflow callback runs with the interrupted user context's `pt_regs` in hand:

  watch(addr,len,access)   -> a hardware watchpoint armed on the target task
                              through the kernel perf/breakpoint API; the
                              callback logs pc + data address (dmesg)
  break(pc) + set-reg      -> an execution breakpoint whose callback rewrites a
                              register in the interrupted frame: flip a branch
                              decision without touching one byte of code
  read/write memory        -> `access_process_vm` on the target from the driver
                              (patch data, dump buffers), no process_vm_* syscalls

Three artifacts, one per route, each with its gate (all from
`references/kernel-and-environment-hardening.md` §4a):

  kpm        KernelPatch/APatch KPM -- needs a KernelPatch-patched boot image
             plus a bare-metal ARM64 toolchain (aarch64-none-elf-gcc, NOT NDK)
  lkm        out-of-tree module -- needs kernel source matching the device's
             exact vermagic, and on >= 5.7 a way to resolve unexported symbols
  userspace  a Magisk/KernelSU-format module skeleton -- an honest carrier for
             the config and the install path; it CANNOT itself arm a watchpoint
             on another process, and says so in its own README

Measured vs unverified
----------------------
`gates`, `generate` and `verify` run on the host
(docs/tool-verification/EXTENSION-kernel-instrument.md). **No kernel-side file
has been compiled or loaded anywhere, by anyone in this repository's passes.**
Every generated kernel file says so in its own header. The register-rewrite
action is the most experimental part of the design: rewriting user pt_regs in a
perf overflow callback is mechanically what a ptrace stop does, but this
repository never ran it, and on some paths the callback runs with interrupts
disabled where you must not sleep. Treat the template as a starting point that
removes the blank page, never as a weapon that has been fired.

Examples
  python kernel_instrument_scaffold.py gates
  python kernel_instrument_scaffold.py generate --out work/kwatch --pid 12345 \\
      --watch 0x7b2000123456:8:w
  python kernel_instrument_scaffold.py generate --out work/kwatch --pid 12345 \\
      --break 0x7b20001234c0 --set-reg x0=0x1
  python kernel_instrument_scaffold.py verify --dir work/kwatch
"""
